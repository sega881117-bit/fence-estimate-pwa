import assert from 'node:assert/strict';
import {BUNDLED_PRICES, PRICE_CHECK_INTERVAL, PRICE_RETRY_INTERVAL, makeDefaultPriceCache, readPriceCache, needsPriceCheck, recordPriceCheck, acceptPriceUpdate, fetchPriceCatalog} from '../lib/price-cache.mjs';

const base = makeDefaultPriceCache();
const now = base.checkedAt;
assert.equal(base.catalog.profile_single_2_0, 2100);
assert.equal(needsPriceCheck(base, now), false);
assert.equal(needsPriceCheck(base, now + PRICE_CHECK_INTERVAL - 1), false);
assert.equal(needsPriceCheck(base, now + PRICE_CHECK_INTERVAL), true);
assert.deepEqual(readPriceCache('{broken', now), base);
assert.deepEqual(readPriceCache(JSON.stringify({...base, catalog: {profile_single_2_0: 1}}), now), base);
const unchanged = recordPriceCheck(base, {...BUNDLED_PRICES, version:'2026-10-28'}, now + PRICE_CHECK_INTERVAL);
assert.equal(unchanged.available, null);
assert.equal(needsPriceCheck(unchanged, now + PRICE_CHECK_INTERVAL + 1), false);
const changed = recordPriceCheck(base, {...BUNDLED_PRICES, profile_single_2_0: 2200, version:'2026-10-28'}, now + PRICE_CHECK_INTERVAL);
assert.equal(changed.catalog.profile_single_2_0, 2100);
assert.equal(changed.available.catalog.profile_single_2_0, 2200);
assert.equal(readPriceCache(JSON.stringify(changed), changed.checkedAt).catalog.profile_single_2_0, 2100);
const accepted = acceptPriceUpdate(changed);
assert.equal(accepted.catalog.profile_single_2_0, 2200);
assert.equal(accepted.available, null);
assert.equal(base.catalog.profile_single_2_0, 2100);
assert.throws(()=>recordPriceCheck(base, {error:'not_allowed'}));
assert.throws(()=>recordPriceCheck(base, {...BUNDLED_PRICES, delivery_0_60: 0}));
const failed = {...base, attemptedAt: now + PRICE_CHECK_INTERVAL};
assert.equal(needsPriceCheck(failed, failed.attemptedAt + PRICE_RETRY_INTERVAL - 1), false);
assert.equal(needsPriceCheck(failed, failed.attemptedAt + PRICE_RETRY_INTERVAL), true);
assert.equal(needsPriceCheck({...base, checkedAt: now + PRICE_CHECK_INTERVAL}, now), true);
const neverResponds = (_url, {signal}) => new Promise((_resolve,reject) => signal.addEventListener('abort',()=>reject(new Error('aborted')), {once:true}));
await assert.rejects(fetchPriceCatalog('https://example.invalid', {fetchImpl:neverResponds, timeoutMs:15}), /aborted/);
assert.equal(base.catalog.profile_single_2_0, 2100);
console.log('PASS: immediate fallback, weekly checks, corrupted cache, pending updates, explicit acceptance, failed retry and bounded timeout');
